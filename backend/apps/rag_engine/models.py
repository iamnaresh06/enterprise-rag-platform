import uuid
from django.db import models
from apps.authentication.models import Tenant


class QueryAuditLog(models.Model):
    """
    Enterprise Audit Log recording user queries, retrieved chunks, 
    generated responses, and performance telemetry for compliance & observability.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )
    tenant = models.ForeignKey(
        Tenant,
        on_delete=models.CASCADE,
        related_name='query_logs'
    )
    query_text = models.TextField(
        help_text="User's original natural language prompt"
    )
    retrieved_chunks = models.JSONField(
        default=list,
        help_text="Metadata of chunks retrieved from Pinecone with similarity scores"
    )
    response_text = models.TextField(
        help_text="Synthesized response generated by the LLM"
    )
    latency_ms = models.FloatField(
        default=0.0,
        help_text="Total end-to-end execution latency in milliseconds"
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True
    )

    class Meta:
        db_table = 'query_audit_logs'
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.tenant.name} - Query at {self.created_at}"
